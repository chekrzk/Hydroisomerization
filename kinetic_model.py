import numpy as np
import matplotlib.pyplot as plt
from scipy.integrate import solve_ivp


# ============================================================
# 1. КИНЕТИЧЕСКИЕ ПАРАМЕТРЫ
# ============================================================

# Температура: 320 °C
# Значения из таблицы 3 статьи, мин^-1

k1 = 0.19300
k_minus_1 = 0.05627
k2 = 0.00314
k3 = 0.00475


# ============================================================
# 2. СТЕХИОМЕТРИЧЕСКИЕ КОЭФФИЦИЕНТЫ
# ============================================================

# В статье:
#
# a1 = 1
# b1 = 1
# c1 = 0.73
# d1 = 1.27
#
# a2 = 1
# b2 = 1
# c2 = 0.8
# d2 = 1.2

a1 = 1.0
b1 = 1.0
c1 = 0.73
d1 = 1.27

a2 = 1.0
b2 = 1.0
c2 = 0.80
d2 = 1.20


# ============================================================
# 3. СИСТЕМА ДИФФЕРЕНЦИАЛЬНЫХ УРАВНЕНИЙ
# ============================================================

def kinetic_model(t, y):
    """
    y[0] = y1 = n-C16
    y[1] = y2 = iso-C16
    y[2] = y3 = H2
    y[3] = y4 = жидкие продукты крекинга C6-C14
    y[4] = y5 = газообразные продукты крекинга C2-C5
    """

    y1, y2, y3, y4, y5 = y

    # --------------------------------------------------------
    # Скорости реакций
    # --------------------------------------------------------

    # Обратимая изомеризация:
    #
    # n-C16 <-> iso-C16
    #
    # w1 = k1*y1 - k(-1)*y2

    w1 = k1 * y1 - k_minus_1 * y2


    # Крекинг n-C16:
    #
    # n-C16 + H2 -> продукты

    w2 = k2 * (y1 ** a1) * (y3 ** b1)


    # Крекинг iso-C16:
    #
    # iso-C16 + H2 -> продукты

    w3 = k3 * (y2 ** a2) * (y3 ** b2)


    # --------------------------------------------------------
    # Дифференциальные уравнения
    # --------------------------------------------------------

    dy1_dt = -w1 - a1 * w2

    dy2_dt = w1 - a2 * w3

    dy3_dt = -b1 * w2 - b2 * w3

    dy4_dt = c1 * w2 + c2 * w3

    dy5_dt = d1 * w2 + d2 * w3


    return [
        dy1_dt,
        dy2_dt,
        dy3_dt,
        dy4_dt,
        dy5_dt
    ]


# ============================================================
# 4. НАЧАЛЬНЫЕ УСЛОВИЯ
# ============================================================

# По графикам статьи начальная смесь примерно:
#
# n-C16 ≈ 0.07
# H2    ≈ 0.93
#
# Остальных веществ в начале нет.
#
# В сумме:
#
# 0.07 + 0.93 = 1

y0 = [
    0.07,   # y1 n-C16
    0.00,   # y2 iso-C16
    0.93,   # y3 H2
    0.00,   # y4 жидкие продукты
    0.00    # y5 газообразные продукты
]


# ============================================================
# 5. ВРЕМЯ
# ============================================================

t_start = 0.0
t_end = 60.0

# Точки только для красивой отрисовки линии.
# Сам BDF использует собственный адаптивный шаг.
t_eval = np.linspace(t_start, t_end, 601)


# ============================================================
# 6. РЕШЕНИЕ ЗАДАЧИ КОШИ
# ============================================================

solution = solve_ivp(
    fun=kinetic_model,

    # интервал решения
    t_span=(t_start, t_end),

    # начальные условия
    y0=y0,

    # Неявный многошаговый метод.
    # По классу наиболее близок к методу Гира,
    # применявшемуся авторами статьи.
    method="BDF",

    # Где хотим получить значения для графика.
    # Это НЕ шаг интегрирования.
    t_eval=t_eval,

    # Требования к точности
    rtol=1e-9,
    atol=1e-12
)


# Проверяем, успешно ли решил интегратор
if not solution.success:
    raise RuntimeError(
        f"Ошибка интегрирования: {solution.message}"
    )


# ============================================================
# 7. РЕЗУЛЬТАТЫ РЕШЕНИЯ
# ============================================================

t = solution.t

y1 = solution.y[0]
y2 = solution.y[1]
y3 = solution.y[2]
y4 = solution.y[3]
y5 = solution.y[4]


