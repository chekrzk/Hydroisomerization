y1_model_at_exp = np.interp(t_exp, t, y1)
y2_model_at_exp = np.interp(t_exp, t, y2)
y4_model_at_exp = np.interp(t_exp, t, y4)
y5_model_at_exp = np.interp(t_exp, t, y5)


def print_error(name, model, exp):

    # Не считаем относительную ошибку там,
    # где экспериментальное значение равно нулю.

    mask = exp != 0

    relative_error = (
        np.abs(model[mask] - exp[mask])
        / np.abs(exp[mask])
        * 100
    )

    print()
    print(name)

    for t_i, model_i, exp_i in zip(
        t_exp,
        model,
        exp
    ):
        print(
            f"t={t_i:5.1f}: "
            f"model={model_i:.6f}, "
            f"exp={exp_i:.6f}"
        )

    if len(relative_error) > 0:
        print(
            f"Средняя относительная ошибка: "
            f"{np.mean(relative_error):.2f}%"
        )


print()
