import numpy as np
import matplotlib.pyplot as plt
from scipy.integrate import solve_ivp


# ============================================================
# 1. УСЛОВИЯ
# ============================================================

TEMPERATURE_C = 320.0
TEMPERATURE_K = TEMPERATURE_C + 273.15

# В статье используется:
# R = 2 кал / (моль * K)
R = 2.0

# H+ присутствует в схеме,
# но отдельной переменной концентрации для него нет.
# Пока считаем его активность постоянной.
H_PLUS = 1.0


# ============================================================
# 2. ПАРАМЕТРЫ АРРЕНИУСА ИЗ ТАБЛИЦЫ 4
#
# Формат:
# reaction: (E, ln(k0))
#
# E     — ккал/моль
# ln k0 — ln(мин^-1)
# ============================================================

ARRHENIUS_PARAMS = {

    # Прямые реакции
    1:  (52.2, 45.58),
    2:  (52.5, 47.39),
    3:  (40.1, 37.17),
    4:  (33.3, 29.66),
    5:  (51.4, 44.64),
    6:  (50.4, 44.01),
    7:  (40.2, 33.25),
    8:  (51.0, 43.65),
    9:  (48.4, 46.68),
    10: (48.7, 44.81),
    11: (59.4, 48.41),
    12: (27.6, 21.62),
    13: (36.3, 33.93),
    14: (51.9, 45.00),
    15: (35.1, 33.06),

    # Обратные реакции
    -1:  (82.8, 76.85),
    -2:  (1.2,  0.01),
    -3:  (10.4, 6.82),
    -4:  (1.6,  2.32),
    -5:  (14.1, 10.58),
    -9:  (89.2, 77.23),
    -10: (2.6,  2.58),
    -13: (50.6, 43.82),
    -14: (79.6, 66.27),
}


# ============================================================
# 3. УРАВНЕНИЕ АРРЕНИУСА
# ============================================================

def arrhenius(E_kcal, ln_k0, temperature_K):
    """
    k = k0 * exp(-E / RT)

    Так как:
        ln(k0) дан непосредственно,

    получаем:
        k = exp(ln(k0) - E/(RT))

    E переводим:
        ккал -> кал
    """

    E_cal = E_kcal * 1000.0

    return np.exp(
        ln_k0 - E_cal / (R * temperature_K)
    )


def calculate_rate_constants(temperature_K):
    k = {}

    for reaction, (E, ln_k0) in ARRHENIUS_PARAMS.items():
        k[reaction] = arrhenius(
            E,
            ln_k0,
            temperature_K
        )

    return k


k = calculate_rate_constants(TEMPERATURE_K)


# ============================================================
# 4. ПЕЧАТАЕМ ПОЛУЧЕННЫЕ КОНСТАНТЫ
# ============================================================

print("Константы скорости при", TEMPERATURE_C, "°C")
print()

for reaction in ARRHENIUS_PARAMS:
    print(
        f"k[{reaction:>3}] = {k[reaction]:.8g} 1/мин"
    )


# ============================================================
# 5. КИНЕТИЧЕСКАЯ МОДЕЛЬ
# ============================================================

def kinetic_model(t, y):

    (
        y1,
        y2,
        y3,
        y4,
        y5,
        y6,
        y7,
        y8,
        y9,
        y10,
        y11,
        y12,
        y13,
        y14,
        y15
    ) = y


    # ========================================================
    # РЕАКЦИЯ 1
    #
    # n-C16H34 ⇄ n-C16H32 + H2
    #
    # y1 ⇄ y7 + y4
    # ========================================================

    w1_forward = k[1] * y1

    w1_reverse = (
        k[-1]
        * y7
        * y4
    )

    w1 = w1_forward - w1_reverse


    # ========================================================
    # РЕАКЦИЯ 2
    #
    # n-C16H32 + H+ ⇄ n-C16H33+
    #
    # y7 ⇄ y8
    #
    # H+ считаем постоянным.
    # ========================================================

    w2_forward = (
        k[2]
        * y7
        * H_PLUS
    )

    w2_reverse = (
        k[-2]
        * y8
    )

    w2 = w2_forward - w2_reverse


    # ========================================================
    # РЕАКЦИЯ 3
    #
    # n-C16H33+ ⇄ iso-C16H33+ (моно)
    #
    # y8 ⇄ y9
    # ========================================================

    w3 = (
        k[3] * y8
        -
        k[-3] * y9
    )


    # ========================================================
    # РЕАКЦИЯ 4
    #
    # n-C16H33+ ⇄ iso-C16H33+ (мульти)
    #
    # y8 ⇄ y10
    # ========================================================

    w4 = (
        k[4] * y8
        -
        k[-4] * y10
    )


    # ========================================================
    # РЕАКЦИЯ 5
    #
    # iso-C16H33+ (моно)
    #       ⇄
    # iso-C16H33+ (мульти)
    #
    # y9 ⇄ y10
    # ========================================================

    w5 = (
        k[5] * y9
        -
        k[-5] * y10
    )


    # ========================================================
    # РЕАКЦИЯ 6
    #
    # y8 -> y11 + y12
    #
    # крекинг
    # ========================================================

    w6 = k[6] * y8


    # ========================================================
    # РЕАКЦИЯ 7
    #
    # y9 -> y11 + y12
    # ========================================================

    w7 = k[7] * y9


    # ========================================================
    # РЕАКЦИЯ 8
    #
    # y10 -> y11 + y12
    # ========================================================

    w8 = k[8] * y10


    # ========================================================
    # РЕАКЦИЯ 9
    #
    # iso-C16H33+ (моно)
    #       ⇄
    # iso-C16H32 (моно) + H+
    #
    # y9 ⇄ y13
    # ========================================================

    w9_forward = (
        k[9]
        * y9
    )

    w9_reverse = (
        k[-9]
        * y13
        * H_PLUS
    )

    w9 = w9_forward - w9_reverse


    # ========================================================
    # РЕАКЦИЯ 10
    #
    # iso-C16H33+ (мульти)
    #       ⇄
    # iso-C16H32 (мульти) + H+
    #
    # y10 ⇄ y14
    # ========================================================

    w10_forward = (
        k[10]
        * y10
    )

    w10_reverse = (
        k[-10]
        * y14
        * H_PLUS
    )

    w10 = w10_forward - w10_reverse


    # ========================================================
    # РЕАКЦИЯ 11
    #
    # y12 -> y15 + H+
    # ========================================================

    w11 = k[11] * y12


    # ========================================================
    # РЕАКЦИЯ 12
    #
    # y11 + H2 -> y5
    # ========================================================

    w12 = (
        k[12]
        * y11
        * y4
    )


    # ========================================================
    # РЕАКЦИЯ 13
    #
    # iso-C16H32 (моно) + H2
    #           ⇄
    # iso-C16H34 (моно)
    #
    # y13 + y4 ⇄ y2
    # ========================================================

    w13_forward = (
        k[13]
        * y13
        * y4
    )

    w13_reverse = (
        k[-13]
        * y2
    )

    w13 = w13_forward - w13_reverse


    # ========================================================
    # РЕАКЦИЯ 14
    #
    # iso-C16H32 (мульти) + H2
    #           ⇄
    # iso-C16H34 (мульти)
    #
    # y14 + y4 ⇄ y3
    # ========================================================

    w14_forward = (
        k[14]
        * y14
        * y4
    )

    w14_reverse = (
        k[-14]
        * y3
    )

    w14 = w14_forward - w14_reverse


    # ========================================================
    # РЕАКЦИЯ 15
    #
    # y15 + H2 -> y6
    #
    # В схеме статьи стрелка обратимая.
    # НО в таблице 4 отсутствует k[-15].
    #
    # Поэтому пока используем только прямую реакцию.
    # ========================================================

    w15 = (
        k[15]
        * y15
        * y4
    )


    # ========================================================
    # 6. 15 ДИФФЕРЕНЦИАЛЬНЫХ УРАВНЕНИЙ
    # ========================================================


    # n-C16H34
    dy1 = -w1


    # iso-C16H34 mono
    dy2 = w13


    # iso-C16H34 multi
    dy3 = w14


    # H2
    #
    # создаётся в реакции 1;
    # расходуется в 12, 13, 14, 15
    dy4 = (
        +w1
        -w12
        -w13
        -w14
        -w15
    )


    # лёгкие насыщенные продукты
    dy5 = w12


    # тяжёлые насыщенные продукты крекинга
    dy6 = w15


    # n-C16H32
    dy7 = (
        +w1
        -w2
    )


    # n-C16H33+
    dy8 = (
        +w2
        -w3
        -w4
        -w6
    )


    # iso-C16H33+ mono
    dy9 = (
        +w3
        -w5
        -w7
        -w9
    )


    # iso-C16H33+ multi
    dy10 = (
        +w4
        +w5
        -w8
        -w10
    )


    # лёгкие олефины
    dy11 = (
        +w6
        +w7
        +w8
        -w12
    )


    # тяжёлый карбоний-ион продукта крекинга
    dy12 = (
        +w6
        +w7
        +w8
        -w11
    )


    # iso-C16H32 mono
    dy13 = (
        +w9
        -w13
    )


    # iso-C16H32 multi
    dy14 = (
        +w10
        -w14
    )


    # тяжёлые олефины
    dy15 = (
        +w11
        -w15
    )


    return np.array([
        dy1,
        dy2,
        dy3,
        dy4,
        dy5,
        dy6,
        dy7,
        dy8,
        dy9,
        dy10,
        dy11,
        dy12,
        dy13,
        dy14,
        dy15
    ])


# ============================================================
# 7. НАЧАЛЬНЫЕ УСЛОВИЯ
# ============================================================

# Судя по рис. 4:
#
# y1 ≈ 0.07
# y4 ≈ 0.93
#
# остальные компоненты в начале отсутствуют.

y0 = np.zeros(15)

y0[0] = 0.07     # y1
y0[3] = 0.93     # y4 = H2


# ============================================================
# 8. ВРЕМЕННОЙ ИНТЕРВАЛ
# ============================================================

t_start = 0.0
t_end = 60.0

t_eval = np.linspace(
    t_start,
    t_end,
    1000
)


# ============================================================
# 9. ЧИСЛЕННОЕ РЕШЕНИЕ
# ============================================================

solution = solve_ivp(
    fun=kinetic_model,
    t_span=(t_start, t_end),
    y0=y0,

    # BDF выбран специально:
    #
    # 1. система потенциально жёсткая;
    # 2. статья использует метод Гира
    #    переменного порядка;
    # 3. BDF относится к тому же классу
    #    неявных многошаговых методов.
    method="BDF",

    t_eval=t_eval,

    rtol=1e-9,
    atol=1e-12,

    max_step=0.25
)


if not solution.success:
    raise RuntimeError(solution.message)


t = solution.t
Y = solution.y


